"""Planner agent: decomposes user goals into structured, dependency-ordered tasks."""

from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional
import uuid
from pydantic import BaseModel, Field

from codeagent.agents.base_agent import AgentContext, AgentRole, AgentStatus, BaseAgent
from codeagent.agents.task_scheduler import DependencyCycleError, TaskScheduler, WorkflowTask
from codeagent.config.settings import Settings, get_settings
from codeagent.intelligence.project_manager import ProjectManager
from codeagent.llm.client import LLMClient
from codeagent.llm.structured import StructuredResponseEngine


class PlanTaskSpec(BaseModel):
    """Structured plan task definition generated by PlannerAgent."""

    task_id: str = Field(default_factory=lambda: f"task_{uuid.uuid4().hex[:8]}")
    task_name: str
    description: str
    assigned_agent: str = "coder"  # coder, debugger, reviewer
    priority: int = 5
    dependencies: List[str] = Field(default_factory=list)
    required_input: Dict[str, Any] = Field(default_factory=dict)
    expected_output: Dict[str, Any] = Field(default_factory=dict)
    acceptance_criteria: List[str] = Field(default_factory=list)
    risk_level: str = "LOW"
    estimated_complexity: str = "LOW"


class PlannerInput(BaseModel):
    """Input parameters provided to the PlannerAgent."""

    goal: str
    workflow_type: str = "BUILD_PROJECT"
    project_type: Optional[str] = None
    context_summary: Optional[str] = None
    target_files: Optional[List[str]] = None


class PlannerOutput(BaseModel):
    """Structured implementation plan generated by PlannerAgent."""

    plan_id: str = Field(default_factory=lambda: f"plan_{uuid.uuid4().hex[:8]}")
    project_type: str = "unknown"
    summary: str
    tasks: List[PlanTaskSpec] = Field(default_factory=list)
    identified_risks: List[str] = Field(default_factory=list)
    architectural_notes: str = ""


class PlannerAgent(BaseAgent):
    """Analyzes requirements, inspects project context, and creates structured task plans."""

    def __init__(
        self,
        agent_id: Optional[str] = None,
        llm_client: Optional[LLMClient] = None,
        project_manager: Optional[ProjectManager] = None,
        settings: Optional[Settings] = None,
    ) -> None:
        """Initialize PlannerAgent."""
        cfg = settings or get_settings()
        target_model = cfg.planner_model or cfg.agent_model or cfg.model_name
        super().__init__(
            agent_id=agent_id or f"planner_{uuid.uuid4().hex[:8]}",
            name="PlannerAgent",
            role=AgentRole.PLANNER,
            description="Decomposes user requests into structured, dependency-ordered tasks",
            system_instructions=(
                "You are the Planner Agent. Your job is to break down coding goals into concrete, "
                "small, dependency-ordered tasks for Coder, Debugger, and Reviewer. "
                "Never invent non-existent files without checking project structure. "
                "Never execute code yourself."
            ),
            capabilities=["task_decomposition", "dependency_ordering", "risk_analysis", "project_inspection"],
            tools=["analyze_project", "scan_project", "search_code", "get_project_architecture", "get_project_memory"],
            input_schema=PlannerInput,
            output_schema=PlannerOutput,
            settings=cfg,
        )
        self.llm_client = llm_client
        self.project_manager = project_manager
        self.model_name = target_model
        self.structured_engine = StructuredResponseEngine()

    def execute(self, input_data: Any, context: Optional[AgentContext] = None) -> PlannerOutput:
        """Generate a structured plan for the given goal."""
        self.status = AgentStatus.BUSY
        plan_input = self.validate_input(input_data)
        assert isinstance(plan_input, PlannerInput)

        # 1. Inspect existing project structure
        existing_info = self._inspect_project_environment(context)
        detected_type = plan_input.project_type or existing_info.get("project_type", "python")

        # 2. Generate plan via LLM if available and online, else deterministic template
        output = None
        if self.llm_client:
            try:
                is_online, _ = self.llm_client.check_connection(timeout=2.0)
                if is_online:
                    output = self._generate_plan_llm(plan_input, existing_info)
            except Exception:
                output = None

        if not output:
            output = self._generate_fallback_plan(plan_input, detected_type, existing_info)

        # 3. Validate DAG acyclic property
        scheduler = TaskScheduler(workflow_id=context.workflow_id if context else "wf_plan")
        for t in output.tasks:
            # Map assigned_agent to AgentRole
            role_val = AgentRole.CODER
            if t.assigned_agent.lower() == "debugger":
                role_val = AgentRole.DEBUGGER
            elif t.assigned_agent.lower() == "reviewer":
                role_val = AgentRole.REVIEWER
            scheduler.add_task(
                WorkflowTask(
                    task_id=t.task_id,
                    workflow_id=scheduler.workflow_id,
                    name=t.task_name,
                    description=t.description,
                    assigned_agent=role_val,
                    priority=t.priority,
                    dependencies=t.dependencies,
                    required_input=t.required_input,
                    expected_output=t.expected_output,
                    acceptance_criteria=t.acceptance_criteria,
                    risk_level=t.risk_level,
                    estimated_complexity=t.estimated_complexity,
                )
            )

        self.status = AgentStatus.COMPLETED
        return output

    def _inspect_project_environment(self, context: Optional[AgentContext] = None) -> Dict[str, Any]:
        """Collect existing project architecture and structure."""
        info: Dict[str, Any] = {"project_type": "python", "files": [], "frameworks": []}
        if self.project_manager:
            try:
                analysis = self.project_manager.project_analyzer.analyze(
                    self.project_manager.active_workspace_path or Path.cwd()
                )
                info["project_type"] = analysis.project_type.value
                info["frameworks"] = [f.name for f in analysis.frameworks]
                info["entry_points"] = analysis.entry_points
            except Exception:
                pass
        return info

    def _generate_plan_llm(self, plan_input: PlannerInput, existing_info: Dict[str, Any]) -> PlannerOutput:
        """Prompt Ollama using StructuredResponseEngine for PlannerOutput."""
        prompt = (
            f"User Goal: {plan_input.goal}\n"
            f"Workflow Type: {plan_input.workflow_type}\n"
            f"Detected Project Type: {existing_info.get('project_type')}\n"
            f"Detected Frameworks: {existing_info.get('frameworks')}\n\n"
            "Generate a structured multi-step implementation plan. "
            "Decompose into individual tasks assigned to 'coder', 'debugger', or 'reviewer'. "
            "Ensure dependencies do not contain cycles."
        )
        return self.structured_engine.generate_structured(
            client=self.llm_client._client,
            prompt=prompt,
            schema_class=PlannerOutput,
            model=self.model_name,
            system_prompt=self.system_instructions,
        )

    def _generate_fallback_plan(
        self, plan_input: PlannerInput, project_type: str, existing_info: Dict[str, Any]
    ) -> PlannerOutput:
        """Deterministic plan generator when LLM is unavailable or for offline testing."""
        w_type = plan_input.workflow_type.upper()
        tasks: List[PlanTaskSpec] = []
        risks: List[str] = ["Unexpected regression in existing test cases", "Dependency version conflicts"]

        if w_type == "FIX_BUG":
            t1_id = f"task_{uuid.uuid4().hex[:6]}"
            t2_id = f"task_{uuid.uuid4().hex[:6]}"
            t3_id = f"task_{uuid.uuid4().hex[:6]}"
            tasks = [
                PlanTaskSpec(
                    task_id=t1_id,
                    task_name="Diagnose Error & Root Cause",
                    description=f"Analyze error traceback for: {plan_input.goal}",
                    assigned_agent="debugger",
                    priority=9,
                    dependencies=[],
                    acceptance_criteria=["Root cause identified and verified"],
                ),
                PlanTaskSpec(
                    task_id=t2_id,
                    task_name="Apply Fix and Verify Tests",
                    description="Apply minimal patch and rerun affected tests",
                    assigned_agent="coder",
                    priority=8,
                    dependencies=[t1_id],
                    acceptance_criteria=["Failing test passes without regression"],
                ),
                PlanTaskSpec(
                    task_id=t3_id,
                    task_name="Independent Code Review",
                    description="Inspect patch for correctness, security, and edge cases",
                    assigned_agent="reviewer",
                    priority=7,
                    dependencies=[t2_id],
                    acceptance_criteria=["Reviewer decision is APPROVED"],
                ),
            ]
        elif w_type == "CODE_REVIEW":
            t1_id = f"task_{uuid.uuid4().hex[:6]}"
            tasks = [
                PlanTaskSpec(
                    task_id=t1_id,
                    task_name="Full Codebase Review",
                    description=f"Inspect modified files for {plan_input.goal}",
                    assigned_agent="reviewer",
                    priority=8,
                    dependencies=[],
                    acceptance_criteria=["Comprehensive review findings logged"],
                )
            ]
        else:  # BUILD_PROJECT or ADD_FEATURE or REFACTOR_PROJECT
            t1_id = f"task_{uuid.uuid4().hex[:6]}"
            t2_id = f"task_{uuid.uuid4().hex[:6]}"
            t3_id = f"task_{uuid.uuid4().hex[:6]}"
            tasks = [
                PlanTaskSpec(
                    task_id=t1_id,
                    task_name="Implement Core Components",
                    description=f"Write code fulfilling: {plan_input.goal}",
                    assigned_agent="coder",
                    priority=8,
                    dependencies=[],
                    acceptance_criteria=["Required files created or updated with passing syntax"],
                ),
                PlanTaskSpec(
                    task_id=t2_id,
                    task_name="Execute Verification Tests",
                    description="Run project test suite and verify changes",
                    assigned_agent="coder",
                    priority=7,
                    dependencies=[t1_id],
                    acceptance_criteria=["All test assertions pass"],
                ),
                PlanTaskSpec(
                    task_id=t3_id,
                    task_name="Independent Quality Review",
                    description="Evaluate implementation across Correctness, Quality, Security, and Testing",
                    assigned_agent="reviewer",
                    priority=6,
                    dependencies=[t2_id],
                    acceptance_criteria=["Review decision is APPROVED"],
                ),
            ]

        return PlannerOutput(
            project_type=project_type,
            summary=f"Structured plan for {plan_input.goal} ({w_type})",
            tasks=tasks,
            identified_risks=risks,
            architectural_notes=f"Generated deterministic plan with {len(tasks)} tasks.",
        )
